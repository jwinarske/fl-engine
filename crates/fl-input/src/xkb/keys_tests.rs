//! The embedder's tests of what is around the tracker, ported under their
//! names: `fl_keyboard_manager_test.cc` (layouts, modifiers, pressed
//! state), `fl_key_channel_responder_test.cc` (the legacy message). The
//! manager's cases of who answered (`EngineHandledChannelNotHandledSync`
//! and the rest) are the shell's, where the waiting is.

use std::time::Duration;

use super::*;
use crate::KeyEventType;

const CODE_KEY_A: u16 = 0x26;
const CODE_KEY_M: u16 = 0x3a;
const CODE_DIGIT1: u16 = 0x0a;
const CODE_MINUS: u16 = 0x14;
const CODE_SEMICOLON: u16 = 0x2f;
const CODE_BRACKET_LEFT: u16 = 0x22;

/// `gdk_keyval_to_unicode`, for the keysyms these cases use.
fn unicode(keyval: u32) -> u32 {
    match keyval {
        0x20..=0xff => keyval,
        0x6c6 => 'ф' as u32, // Cyrillic_ef
        0x6c8 => 'х' as u32, // Cyrillic_ha
        _ => 0,
    }
}

fn key(pressed: bool, keycode: u16, keyval: u32, group: u8) -> XkbKey {
    XkbKey {
        pressed,
        keycode,
        keyval,
        unicode: unicode(keyval),
        group,
        ..XkbKey::default()
    }
}

/// The embedder's mock layout data: a group's keysyms, two shift levels a
/// keycode.
fn mock<'a>(layout: &'a [Option<&'a [u32; 256]>]) -> impl Fn(u16, u8, u8) -> u32 + 'a {
    move |keycode, group, level| {
        assert!(level < 2);
        let group = layout[usize::from(group)];
        #[allow(clippy::expect_used)]
        let group = group.expect("a group the layout has");
        group[usize::from(keycode) * 2 + usize::from(level)]
    }
}

/// `CorrectLogicalKeyForLayouts`.
#[test]
fn correct_logical_key_for_layouts() {
    let mut keys = Keys::new();
    // A tap; what its down was sent as.
    let mut tap = |keycode: u16, keyval: u32, group: u8, lookup: &dyn Fn(u16, u8, u8) -> u32| {
        let down = keys.handle(&key(true, keycode, keyval, group), lookup);
        keys.handle(&key(false, keycode, keyval, group), lookup);
        assert_eq!(down.data.len(), 1);
        let d = &down.data[0];
        assert_eq!(d.kind, KeyEventType::Down);
        assert!(!d.synthesized);
        (d.logical, d.character.clone().unwrap_or_default())
    };
    let is = |got: (u64, String), logical: u64, character: &str| {
        assert_eq!(got, (logical, character.to_owned()));
    };

    // US keyboard layout. The embedder's mock keymap gives no keysyms.
    let us = |_, _, _| 0;
    is(tap(CODE_KEY_A, 0x61, 0, &us), 0x61, "a");
    is(tap(CODE_KEY_A, 0x41, 0, &us), 0x61, "A"); // Shift-KeyA
    is(tap(CODE_DIGIT1, 0x31, 0, &us), 0x31, "1");
    is(tap(CODE_DIGIT1, 0x21, 0, &us), 0x31, "!"); // Shift-Digit1
    is(tap(CODE_MINUS, 0x2d, 0, &us), 0x2d, "-");
    is(tap(CODE_MINUS, 0x5f, 0, &us), 0x5f, "_"); // Shift-Minus

    // French keyboard layout, group 3, which is when the input method is
    // showing "Fr".
    let french = [Some(&FRENCH_0), None, None, Some(&FRENCH_3)];
    let french = mock(&french);
    is(tap(CODE_KEY_A, 0x71, 3, &french), 0x71, "q");
    is(tap(CODE_KEY_A, 0x51, 3, &french), 0x71, "Q"); // Shift-KeyA
    is(tap(CODE_SEMICOLON, 0x6d, 3, &french), 0x6d, "m"); // ; but prints M
    is(tap(CODE_KEY_M, 0x2c, 3, &french), 0x2c, ","); // M but prints ,
    is(tap(CODE_DIGIT1, 0x26, 3, &french), 0x31, "&");
    is(tap(CODE_DIGIT1, 0x31, 3, &french), 0x31, "1"); // Shift-Digit1
    is(tap(CODE_MINUS, 0x29, 3, &french), 0x29, ")");
    is(tap(CODE_MINUS, 0xb0, 3, &french), 0xb0, "°"); // Shift-Minus

    // French keyboard layout, group 0, which is pressing the "extra key
    // for triggering input method" key once after switching to French IME.
    is(tap(CODE_KEY_A, 0x61, 0, &french), 0x61, "a");
    is(tap(CODE_DIGIT1, 0x31, 0, &french), 0x31, "1");

    // Russian keyboard layout, group 2.
    let russian = [Some(&RUSSIAN_0), None, Some(&RUSSIAN_2)];
    let russian = mock(&russian);
    is(tap(CODE_KEY_A, 0x6c6, 2, &russian), 0x61, "ф");
    is(tap(CODE_DIGIT1, 0x31, 2, &russian), 0x31, "1");
    is(tap(CODE_BRACKET_LEFT, 0x6c8, 2, &russian), 0x5b, "х");

    // Russian keyboard layout, group 0.
    is(tap(CODE_KEY_A, 0x61, 0, &russian), 0x61, "a");
    is(tap(CODE_BRACKET_LEFT, 0x5b, 0, &russian), 0x5b, "[");
}

/// `SynthesizeModifiersIfNeeded`.
#[test]
fn synthesize_modifiers_if_needed() {
    let mut keys = Keys::new();
    // No modifiers pressed.
    assert_eq!(keys.sync_modifiers(0, Duration::from_millis(1000)), None);

    // Press and release each modifier once.
    for (mask, physical, logical) in [
        (state::CONTROL, 0x0007_00e0, 0x2_0000_0100),
        (state::META, 0x0007_00e3, 0x2_0000_0106),
        (state::MOD1, 0x0007_00e2, 0x2_0000_0104),
        (state::SHIFT, 0x0007_00e1, 0x2_0000_0102),
    ] {
        for (state, kind, ms) in [
            (mask, KeyEventType::Down, 1000),
            (0, KeyEventType::Up, 1001),
        ] {
            let time = Duration::from_millis(ms);
            #[allow(clippy::expect_used)]
            let event = keys.sync_modifiers(state, time).expect("an event");
            assert_eq!(event.raw, None);
            assert_eq!(
                event.data,
                [crate::KeyData {
                    timestamp: time,
                    kind,
                    physical,
                    logical,
                    character: None,
                    synthesized: true,
                }]
            );
            assert_eq!(event.answered(), None);
        }
    }
}

/// `GetPressedState`, and `KeyboardChannelGetPressedState`'s half of it.
#[test]
fn get_pressed_state() {
    let mut keys = Keys::new();
    keys.handle(&key(true, CODE_KEY_A, 0x61, 0), |_, _, _| 0);
    assert_eq!(keys.pressed().collect::<Vec<_>>(), [(0x0007_0004, 0x61)]);
}

fn message(raw: &mut RawChannel, pressed: bool, keyval: u32, specified: u64) -> String {
    let bytes = raw.message(&key(pressed, 0x04, keyval, 0), specified);
    #[allow(clippy::expect_used)]
    String::from_utf8(bytes).expect("UTF-8")
}

/// `SendKeyEvent`: a letter "A".
#[test]
fn send_key_event() {
    let mut raw = RawChannel::default();
    assert_eq!(
        message(&mut raw, true, 0x41, 0),
        r#"{"type":"keydown","keymap":"linux","scanCode":4,"toolkit":"gtk","keyCode":65,"modifiers":0,"unicodeScalarValues":65}"#
    );
    assert_eq!(
        message(&mut raw, false, 0x41, 0),
        r#"{"type":"keyup","keymap":"linux","scanCode":4,"toolkit":"gtk","keyCode":65,"modifiers":0,"unicodeScalarValues":65}"#
    );
}

/// `SendNumLockKeyEvent`, `SendCapsLockKeyEvent`, `SendShiftLockKeyEvent`:
/// a lock's bit is set while its key is held.
#[test]
fn send_lock_key_events() {
    for (keyval, bit) in [
        (keysym::NUM_LOCK, 16),
        (keysym::CAPS_LOCK, 2),
        (keysym::SHIFT_LOCK, 2),
    ] {
        let mut raw = RawChannel::default();
        assert_eq!(
            message(&mut raw, true, keyval, 0),
            format!(
                r#"{{"type":"keydown","keymap":"linux","scanCode":4,"toolkit":"gtk","keyCode":{keyval},"modifiers":{bit}}}"#
            )
        );
        assert_eq!(
            message(&mut raw, false, keyval, 0),
            format!(
                r#"{{"type":"keyup","keymap":"linux","scanCode":4,"toolkit":"gtk","keyCode":{keyval},"modifiers":0}}"#
            )
        );
    }
}

/// `UseSpecifiedLogicalKey`.
#[test]
fn use_specified_logical_key() {
    let mut raw = RawChannel::default();
    assert_eq!(
        message(&mut raw, true, 0x41, 888),
        r#"{"type":"keydown","keymap":"linux","scanCode":4,"toolkit":"gtk","keyCode":65,"modifiers":0,"unicodeScalarValues":65,"specifiedLogicalKey":888}"#
    );
}

/// The lock bits of the state are not the message's: those say whether a
/// lock key is held.
#[test]
fn the_message_leaves_out_the_state_s_lock_bits() {
    let mut raw = RawChannel::default();
    let k = XkbKey {
        state: state::SHIFT | state::LOCK | state::MOD2,
        ..key(true, CODE_KEY_A, 0x41, 0)
    };
    let bytes = raw.message(&k, 0);
    assert!(String::from_utf8_lossy(&bytes).contains("\"modifiers\":1,"));
}

/// `FlKeyboardLayoutTest`'s cases: a key past the layout's size has no
/// logical key, and a group is derived once.
#[test]
fn a_layout_keeps_128_keycodes_a_group() {
    let mut layout = Layout::default();
    assert_eq!(layout.logical_key(0, CODE_KEY_A, |_, _, _| 0), 0x61);
    assert_eq!(layout.logical_key(0, 128, |_, _, _| 0), 0);
    // Derived already: the keymap is not asked again.
    assert_eq!(
        layout.logical_key(0, CODE_KEY_M, |_, _, _| unreachable!()),
        0x6d
    );
    // A key that is no goal derives nothing.
    assert_eq!(layout.logical_key(7, 0x09, |_, _, _| unreachable!()), 0);
    assert_eq!(layout.logical_key(255, CODE_KEY_A, |_, _, _| 0), 0x61);
}

